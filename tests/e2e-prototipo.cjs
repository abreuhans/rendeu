// Teste de ponta a ponta do protótipo web (Playwright). Uso: node tests/e2e-prototipo.cjs <pasta-com-index.html> <pasta-prints>
const { chromium } = require('playwright');
const [dir, shots] = process.argv.slice(2);
(async () => {
  const browser = await chromium.launch();
  const erros = [];
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  const page = await ctx.newPage();
  page.on('console', m => { if (m.type() === 'error') erros.push(m.text()); });
  page.on('pageerror', e => erros.push('PAGEERROR ' + e.message));
  const transbordou = async rotulo => {
    const o = await page.evaluate(() => ({ sw: document.documentElement.scrollWidth, w: window.innerWidth }));
    if (o.sw > o.w) console.log('TRANSBORDA em', rotulo, o);
  };
  await page.goto('file://' + dir + '/index.html');
  await page.waitForTimeout(1500);
  await transbordou('inicio');
  await page.screenshot({ path: shots + '/01-inicio.png', fullPage: true });
  await page.click('[data-acao="comecar"]');
  await page.fill('#orcamento', '200');
  await page.click('#cta');
  await page.fill('#cep', '88015200');
  console.log('cep:', await page.inputValue('#cep'), '|', await page.textContent('#cep-msg'));
  await page.click('[data-acao="mercado"][data-id="fort"]');
  await transbordou('mercados');
  await page.screenshot({ path: shots + '/02-mercados.png', fullPage: true });
  await page.click('#cta');
  await page.click('[data-acao="def"][data-k="dieta"][data-v="proteica"]');
  await page.click('#cta');
  await page.click('[data-acao="alternar"][data-k="aparelhos"][data-id="airfryer"]');
  await page.click('[data-acao="alternar"][data-k="despensa"][data-id="arroz"]');
  await page.screenshot({ path: shots + '/03-cozinha.png', fullPage: true });
  await page.click('#cta');
  await page.click('[data-acao="alternar"][data-k="adora"][data-id="frango"]');
  await page.click('[data-acao="alternar"][data-k="naoCome"][data-id="peixe"]');
  await page.click('[data-acao="alternar"][data-k="cozinhas"][data-id="nordestina"]');
  await page.click('#cta');
  await page.click('[data-acao="alternar"][data-k="refeicoes"][data-id="S"]');
  await page.screenshot({ path: shots + '/04-plano.png', fullPage: true });
  await page.click('#cta');
  await page.waitForSelector('.summary', { timeout: 20000 });
  await transbordou('resultado');
  await page.screenshot({ path: shots + '/05-resultado.png', fullPage: true });
  console.log('total', await page.textContent('.total'), await page.textContent('.of'), '| refeições', await page.locator('.meal').count());
  await page.click('.meal >> nth=1');
  await page.waitForSelector('.sheet'); await page.waitForTimeout(500);
  await page.screenshot({ path: shots + '/06-receita.png' });
  const alt = page.locator('.sheet .alts .chip').first();
  if (await alt.count()) { await alt.click(); console.log('aparelho trocado para', await page.locator('.sheet .appl').first().textContent()); }
  const antes = await page.textContent('#titulo-folha');
  await page.click('.sheet [data-acao="trocar"]');
  await page.waitForTimeout(300);
  console.log('troca:', antes, '->', await page.textContent('#titulo-folha'), '|', await page.textContent('#toast'));
  await page.keyboard.press('Escape');
  await page.click('[data-acao="aba"][data-v="compras"]');
  await transbordou('compras');
  await page.screenshot({ path: shots + '/07-compras.png', fullPage: true });
  await page.click('.line >> nth=0');
  await page.click('[data-acao="aba"][data-v="mercados"]');
  await page.screenshot({ path: shots + '/08-mercados.png', fullPage: true });
  await page.click('[data-acao="aba"][data-v="bastidores"]');
  await page.screenshot({ path: shots + '/09-bastidores.png', fullPage: true });
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.click('[data-acao="aba"][data-v="cardapio"]');
  await page.screenshot({ path: shots + '/10-escuro.png', fullPage: true });
  await page.click('.meal >> nth=0');
  await page.waitForSelector('.sheet'); await page.waitForTimeout(500);
  await page.screenshot({ path: shots + '/11-escuro-receita.png' });
  await page.keyboard.press('Escape');
  await page.emulateMedia({ colorScheme: 'light' });
  await page.reload();
  await page.waitForTimeout(700);
  console.log('depois de recarregar, plano continua:', (await page.locator('.summary').count()) > 0);
  await page.click('[data-acao="editar"]');
  await page.fill('#orcamento', '30');
  for (let s = 0; s < 6; s++) await page.click('#cta');
  await page.waitForTimeout(2000);
  await page.screenshot({ path: shots + '/12-problema.png' });
  console.log('problema:', await page.textContent('.q'));
  await page.click('[data-acao="usar-orc"]');
  await page.waitForSelector('.summary', { timeout: 20000 });
  console.log('com o valor sugerido:', await page.textContent('.total'), await page.textContent('.of'));
  const d = await browser.newContext({ viewport: { width: 1360, height: 900 } });
  const dp = await d.newPage();
  dp.on('pageerror', e => erros.push('PAGEERROR desktop ' + e.message));
  await dp.goto('file://' + dir + '/index.html');
  await dp.waitForTimeout(1200);
  await dp.screenshot({ path: shots + '/13-desktop-inicio.png' });
  await dp.click('[data-acao="exemplo"]');
  await dp.waitForSelector('.summary', { timeout: 20000 });
  await dp.screenshot({ path: shots + '/14-desktop-resultado.png' });
  await dp.click('.meal >> nth=2');
  await dp.waitForSelector('.sheet'); await dp.waitForTimeout(500);
  await dp.screenshot({ path: shots + '/15-desktop-receita.png' });
  console.log('erros:', erros.length ? erros : 'nenhum');
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
